#!/usr/bin/env python3
"""Cast Recorder UI glyphs -> res/icons/<name>-<px>.png + res/icons.rc2.

24-unit grid, round caps and joins, white on transparent (tinted at draw time). Every glyph is rasterised at each
device size the app draws (16 and 20 logical px at 100/125/150/175/200/250/300 % DPI), so it is never rescaled at
runtime. The stroke is chosen per device size (in device pixels, quarter-pixel steps, >= 1.5 px) so the weight looks
the same at every DPI instead of thinning to ~1.2 px at 16 px. Requires: pip install cairosvg
"""
import math, cairosvg
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "res" / "icons"
SIZES = [16, 20, 24, 25, 28, 30, 32, 35, 40, 48, 50, 60]   # keep in sync with kIconPx in src/win/main.cpp
# glyph order = enum Glyph in src/win/main.cpp (resource id = 1000 + glyph * 16 + size index)
ORDER = ["record", "pause", "stop", "mic", "mic-muted", "system-audio", "system-audio-muted", "folder", "log", "settings",
         "minimize", "maximize", "restore", "close", "chevron-down", "check", "monitor", "window", "fullscreen",
         "check-circle", "moon", "sun", "play", "remux", "replay", "search"]

def gear():
    pts=[]; n=8
    for i in range(n*4):
        a = i/(n*4)*2*math.pi
        r = 9 if (i%4) in (0,1) else 6.8
        pts.append(f"{12+r*math.cos(a):.2f} {12+r*math.sin(a):.2f}")
    return f'<path d="M{" L".join(pts)} Z"/><circle cx="12" cy="12" r="3"/>'

