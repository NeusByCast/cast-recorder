def stroke_px(px):
    return max(1.5, round(px * 0.075 * 4) / 4)

def svg(body, px):
    sw = stroke_px(px) * 24.0 / px   # device px -> 24-unit viewBox
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="{px}" height="{px}" fill="none" '
            f'stroke="#FFFFFF" stroke-width="{sw:.4f}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')

if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    for f in OUT.glob("*.png"): f.unlink()
    rc = ["// Generated by scripts/gen_icons.py - do not edit. ID = 1000 + glyph * 16 + size index; sizes " + ", ".join(map(str, SIZES)) + " px."]
    for gi, name in enumerate(ORDER):
        body = ICONS[name]
        (OUT / f"{name}.svg").write_text(svg(body, 24))
        for k, px in enumerate(SIZES):
            cairosvg.svg2png(bytestring=svg(body, px).encode(), write_to=str(OUT / f"{name}-{px}.png"), output_width=px, output_height=px)
            rc.append(f'{1000 + gi * 16 + k} RCDATA "icons/{name}-{px}.png"')
    (ROOT / "res" / "icons.rc2").write_text("\n".join(rc) + "\n")
    print(len(ORDER), "glyphs x", len(SIZES), "sizes")
